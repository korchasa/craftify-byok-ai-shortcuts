import SwiftUI

/// Константы для стилей кнопок Craftify
public enum CraftifyButtonConstants {
    /// Основной цвет кнопки
    public static let primaryColor = Color(hex: "ff807d")
    /// Второстепенный цвет кнопки
    public static let secondaryColor = Color(hex: "89e1c5")
    /// Радиус скругления кнопки
    public static let cornerRadius: CGFloat = 20
    /// Горизонтальный отступ для кнопок
    public static let horizontalPadding: CGFloat = 16
    /// Нижний отступ для кнопок
    public static let bottomPadding: CGFloat = 16
    /// Масштаб при нажатии
    public static let pressedScale: CGFloat = 0.97
    /// Левый отступ для заголовка
    public static let titleLeadingPadding: CGFloat = 16
    /// Минимальная высота для Spacer
    public static let spacerMinLength: CGFloat = 0
}
