import SwiftUI

/// Layout constants for color picker UI elements.
public struct ColorPickerLayoutConstants {
    /// The size of the color selection circle.
    public static let circleSize: CGFloat = 30
    /// The spacing between color selection circles.
    public static let circleSpacing: CGFloat = 12
    /// The border width for the selected color circle.
    public static let borderWidth: CGFloat = 3
    /// The vertical spacing between palette elements.
    public static let verticalSpacing: CGFloat = 8
    /// The bottom padding for the color picker.
    public static let bottomPadding: CGFloat = 4
    private init() {}
}
